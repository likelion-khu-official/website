// 랜딩에 노출할 핵심 질문 — 지원 결정에 가장 크게 걸리는 것들만.
// (첫 항목 순서는 랜딩 테스트가 참조하므로 유지)
const CORE_QUESTIONS = [
  '코딩을 전혀 몰라도 지원할 수 있나요?',
  '전공이나 학년 제한이 있나요?',
  '어떤 트랙을 모집하나요?',
  '활동은 구체적으로 어떻게 진행되나요?',
  '활동은 대면으로 진행되나요?',
  '지금 지원할 수 있나요?',
] as const;

const allItems: QA[] = faqGroups.flatMap((g) => g.items);

export const coreFaqs: QA[] = CORE_QUESTIONS.map((q) => {
  const found = allItems.find((item) => item.question === q);
  if (!found) throw new Error(`coreFaqs: "${q}" 문항을 faqGroups에서 찾지 못했습니다.`);
  return found;
});
